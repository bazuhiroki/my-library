export const GENRE_NAMES = GENRES.map((g) => g.name);
export const OTHER = 'その他';
export const shortOf = (name) => (GENRES.find((g) => g.name === name) || { short: name }).short;

const RULES = GENRES.map((g) => ({
  name: g.name,
  kws: g.kw.split(',').map((k) => { const s = k.endsWith('*'); const w = (s ? k.slice(0, -1) : k).normalize('NFKC').toLowerCase(); return { w, s }; }),
}));

// 題名と著者から、いちばんそれらしいジャンルを選ぶ。強いキーワード（*）は2点、ほかは1点。同点なら一覧の上のほうを優先する
export function guessGenre(title, author) {
  const text = (String(title || '') + ' ' + String(author || '')).normalize('NFKC').toLowerCase();
  let best = null;
  for (const r of RULES) {
    let score = 0;
    const hit = [];
    for (const k of r.kws) {
      if (k.w && text.includes(k.w)) { score += k.s ? 2 : 1; hit.push(k.w); }
    }
    if (score > 0 && (!best || score > best.score)) best = { genre: r.name, score, tags: hit };
  }
  if (!best) return { genre: OTHER, tags: [], score: 0 };
  return { genre: best.genre, tags: best.tags.slice(0, 3), score: best.score };
}
